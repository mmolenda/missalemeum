"""Page references for existing chants in the two Te Deum publications.

The older modlitewnik editions share chant pagination. References below come
from its alphabetical indexes and the kancjonał contents supplied by the user.
Only listed locations are recorded; continuation pages are not inferred.
"""

from typing import Optional, Union


def get_pages(
    modlitewnik: Optional[Union[int, tuple[int, ...]]] = None,
    kancjonal: Optional[Union[int, tuple[int, ...]]] = None,
) -> list[str]:
    pages = []
    if modlitewnik is not None:
        numbers = (modlitewnik,) if isinstance(modlitewnik, int) else modlitewnik
        pages.extend(f"Te Deum — modlitewnik, s. {page}" for page in numbers)
    if kancjonal is not None:
        numbers = (kancjonal,) if isinstance(kancjonal, int) else kancjonal
        pages.extend(f"Te Deum — kancjonał, s. {page}" for page in numbers)
    return pages


